import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const expectedProjects = {
    preview: 'namosoubpvwbspuczzqj',
    production: 'tgwbhvutozgcmnthxhzo'
};

const deploymentEnvironment = (process.env.VERCEL_ENV || '')
    .trim()
    .toLowerCase();

if (!Object.hasOwn(expectedProjects, deploymentEnvironment)) {
    throw new Error(
        'Deployment stopped: VERCEL_ENV must be preview or production.'
    );
}

let supabaseUrl;
let publishableKey;

if (deploymentEnvironment === 'preview') {
    supabaseUrl = (process.env.SUPABASE_PREVIEW_URL || '').trim();
    publishableKey =
        (process.env.SUPABASE_PREVIEW_PUBLISHABLE_KEY || '').trim();
} else {
    supabaseUrl = (process.env.SUPABASE_URL || '').trim();
    publishableKey =
        (process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();
}

if (!supabaseUrl) {
    throw new Error('Deployment stopped: SUPABASE_URL is missing.');
}

if (!publishableKey) {
    throw new Error(
        'Deployment stopped: SUPABASE_PUBLISHABLE_KEY is missing.'
    );
}

let parsedUrl;

try {
    parsedUrl = new URL(supabaseUrl);
} catch {
    throw new Error('Deployment stopped: SUPABASE_URL is invalid.');
}

const expectedHost = `${expectedProjects[deploymentEnvironment]}.supabase.co`;

if (
    parsedUrl.protocol !== 'https:' ||
    parsedUrl.hostname !== expectedHost ||
    parsedUrl.pathname !== '/' ||
    parsedUrl.search ||
    parsedUrl.hash
) {
    throw new Error(
        `Deployment stopped: ${deploymentEnvironment} must use ${expectedHost}.`
    );
}

if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(publishableKey)) {
    throw new Error(
        'Deployment stopped: SUPABASE_PUBLISHABLE_KEY is not a valid publishable-key format.'
    );
}

const generatedConfig = `// Generated by scripts/generate-supabase-config.js.
// Do not edit this generated file directly.

const SUPABASE_URL = ${JSON.stringify(supabaseUrl)};
const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(publishableKey)};
const SUPABASE_ANON_KEY = SUPABASE_PUBLISHABLE_KEY;

// Compatibility aliases for existing application scripts.
window.SUPABASE_URL = SUPABASE_URL;
window.SUPABASE_PUBLISHABLE_KEY = SUPABASE_PUBLISHABLE_KEY;
window.SUPABASE_ANON_KEY = SUPABASE_PUBLISHABLE_KEY;

if (typeof supabase !== 'undefined' && typeof supabase.createClient === 'function') {
    try {
        if (!window.supabaseClient) {
            window.supabaseClient = supabase.createClient(
                SUPABASE_URL,
                SUPABASE_PUBLISHABLE_KEY
            );
        }

        window.sbClient = window.supabaseClient;

        console.log('Supabase client initialized successfully.');
    } catch (error) {
        console.error('Supabase initialization failed:', error);
    }
} else {
    console.error('Supabase SDK has not loaded.');
}
`;

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(projectRoot, 'js', 'supabase-config.js');

await writeFile(outputPath, generatedConfig, 'utf8');

console.log(
    `Generated Supabase browser configuration for ${deploymentEnvironment}.`
);
console.log(`Verified Supabase project: ${expectedProjects[deploymentEnvironment]}`);
console.log('Publishable key value was not printed.');